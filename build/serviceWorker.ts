import type { Plugin } from 'vite';

const DEV_UNREGISTER_SW = `
self.addEventListener('install', () => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    self.registration.unregister().then(() => self.clients.matchAll()).then((clients) => {
      for (const client of clients) {
        if ('navigate' in client) {
          client.navigate(client.url);
        }
      }
    }),
  );
});
`.trimStart();

const PRECACHE_EXT_RE = /\.(?:html|js|css|png|jpg|jpeg|webp|gif|svg|ico|woff2?|ttf|eot)$/i;

/** Computes a deterministic FNV-1a + length build fingerprint in pure TypeScript. */
function computeBuildFingerprint(entries: string[]): string {
  let hashA = 0x811c9dc5;
  let hashB = 0x9e3779b9;

  for (const entry of entries) {
    for (let i = 0; i < entry.length; i += 1) {
      const code = entry.charCodeAt(i);
      hashA ^= code;
      hashA = Math.imul(hashA, 0x01000193) >>> 0;
      hashB ^= code + i;
      hashB = Math.imul(hashB, 0x85ebca6b) >>> 0;
    }
  }

  return `${hashA.toString(36)}-${hashB.toString(36)}`;
}

/** Generates the production Service Worker source with embedded version and precache manifest. */
function buildServiceWorkerSource(
  cacheVersion: string,
  precacheUrls: string[],
  supabaseOrigin: string | null,
): string {
  const excludedOrigins = supabaseOrigin ? [supabaseOrigin] : [];

  return `/* Auto-generated by Vite build — Team SPIRIT Static Asset Cache */
const CACHE_VERSION = ${JSON.stringify(cacheVersion)};
const STATIC_CACHE = 'team-spirit-static-' + CACHE_VERSION;
const FONT_CACHE = 'team-spirit-fonts-v1';
const PRECACHE_URLS = ${JSON.stringify(precacheUrls, null, 2)};
const EXCLUDED_ORIGINS = new Set(${JSON.stringify(excludedOrigins)});

const ALLOWED_FONT_ORIGINS = new Set([
  'https://fonts.googleapis.com',
  'https://fonts.gstatic.com',
]);

const STATIC_ASSET_EXT_RE = /\\.(?:js|css|png|jpg|jpeg|webp|gif|svg|ico|woff2?|ttf|eot)$/i;

const EXCLUDED_DATA_PATH_PREFIXES = [
  '/rest/v1/',
  '/auth/v1/',
  '/realtime/v1/',
  '/storage/v1/',
  '/functions/v1/',
  '/api/',
];

function resolveFromScope(relativePath) {
  return new URL(relativePath, self.registration.scope).href;
}

/**
 * Hard exclusion boundary: never intercept or cache live user data, Supabase queries,
 * auth tokens, realtime traffic, mutations, or non-allowlisted third-party APIs.
 */
function shouldBypassStaticCache(request, url) {
  if (request.method !== 'GET') return true;
  if (url.protocol !== 'http:' && url.protocol !== 'https:') return true;

  if (
    EXCLUDED_ORIGINS.has(url.origin) ||
    url.hostname === 'supabase.co' ||
    url.hostname.endsWith('.supabase.co') ||
    url.hostname.endsWith('.supabase.in')
  ) {
    return true;
  }

  if (EXCLUDED_DATA_PATH_PREFIXES.some((prefix) => url.pathname.startsWith(prefix))) {
    return true;
  }

  if (
    request.headers.has('authorization') ||
    request.headers.has('apikey') ||
    request.headers.has('x-client-info')
  ) {
    return true;
  }

  const accept = request.headers.get('accept') || '';
  if (accept.includes('application/json') || accept.includes('application/vnd.pgrst')) {
    return true;
  }

  if (url.origin === self.location.origin && url.pathname.endsWith('/sw.js')) {
    return true;
  }

  if (url.origin !== self.location.origin && !ALLOWED_FONT_ORIGINS.has(url.origin)) {
    return true;
  }

  return false;
}

function isSameOriginStaticAsset(url) {
  if (url.origin !== self.location.origin) return false;
  const scopePathname = new URL(self.registration.scope).pathname;
  const assetsPrefix = scopePathname.endsWith('/') ? scopePathname + 'assets/' : scopePathname + '/assets/';
  return url.pathname.startsWith(assetsPrefix) || STATIC_ASSET_EXT_RE.test(url.pathname);
}

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(STATIC_CACHE)
      .then((cache) =>
        Promise.all(
          PRECACHE_URLS.map((url) => {
            const resolved = resolveFromScope(url);
            return cache.add(new Request(resolved, { cache: 'reload' }));
          }),
        ),
      )
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith('team-spirit-static-') && key !== STATIC_CACHE)
            .map((key) => caches.delete(key)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') {
    self.skipWaiting();
  }
});

async function handleGoogleFontStylesheet(request) {
  const cache = await caches.open(FONT_CACHE);
  const cached = await cache.match(request);

  const networkPromise = fetch(request)
    .then((response) => {
      if (response && response.ok) {
        void cache.put(request, response.clone());
      }
      return response;
    })
    .catch(() => null);

  if (cached) {
    return cached;
  }

  const networkResponse = await networkPromise;
  if (networkResponse) {
    return networkResponse;
  }

  return Response.error();
}

async function handleGoogleFontAsset(request) {
  const cache = await caches.open(FONT_CACHE);
  const cached = await cache.match(request);
  if (cached) {
    return cached;
  }

  const response = await fetch(request);
  if (response && (response.ok || response.type === 'opaque')) {
    await cache.put(request, response.clone());
  }
  return response;
}

async function handleNavigationRequest(request, url) {
  const cache = await caches.open(STATIC_CACHE);
  const isCalendarRoute =
    url.pathname.endsWith('/calendar') || url.pathname.endsWith('/calendar.html');

  const candidatePaths = isCalendarRoute
    ? ['./calendar.html', './index.html']
    : ['./index.html'];

  for (const candidate of candidatePaths) {
    const cached = await cache.match(resolveFromScope(candidate));
    if (cached) {
      return cached;
    }
  }

  return fetch(request);
}

async function handleStaticAssetRequest(request) {
  const cache = await caches.open(STATIC_CACHE);
  const cached = await cache.match(request);
  if (cached) {
    return cached;
  }

  const response = await fetch(request);
  if (response && response.ok && response.type === 'basic') {
    await cache.put(request, response.clone());
  }
  return response;
}

self.addEventListener('fetch', (event) => {
  const { request } = event;
  const url = new URL(request.url);

  // Live user data, Supabase REST/Auth/Realtime, and mutations bypass the static cache completely.
  if (shouldBypassStaticCache(request, url)) {
    return;
  }

  if (url.origin === 'https://fonts.googleapis.com') {
    event.respondWith(handleGoogleFontStylesheet(request));
    return;
  }

  if (url.origin === 'https://fonts.gstatic.com') {
    event.respondWith(handleGoogleFontAsset(request));
    return;
  }

  if (url.origin === self.location.origin && request.mode === 'navigate') {
    event.respondWith(handleNavigationRequest(request, url));
    return;
  }

  if (isSameOriginStaticAsset(url)) {
    event.respondWith(handleStaticAssetRequest(request));
  }
});
`;
}

/**
 * Vite plugin that emits a versioned Service Worker (`sw.js`) precaching all static build assets
 * while handling clean `/calendar` routes in dev/preview and ensuring dev builds never run stale caches.
 */
export function teamSpiritStaticCachePlugin(): Plugin {
  let supabaseOrigin: string | null = null;

  return {
    name: 'team-spirit-static-cache',
    enforce: 'post',

    configResolved(config) {
      const rawUrl = config.env?.VITE_SUPABASE_URL;
      if (typeof rawUrl === 'string') {
        const match = /^(https?:\/\/[^/?#]+)/i.exec(rawUrl.trim());
        supabaseOrigin = match ? match[1] : null;
      }
    },

    configureServer(server) {
      server.middlewares.use('/sw.js', (_req, res) => {
        res.setHeader('Content-Type', 'application/javascript; charset=utf-8');
        res.setHeader('Cache-Control', 'no-store');
        res.end(DEV_UNREGISTER_SW);
      });
    },

    configurePreviewServer(server) {
      server.middlewares.use((req, _res, next) => {
        const incoming = req as { url?: string };
        if (incoming.url === '/calendar' || incoming.url?.startsWith('/calendar?')) {
          incoming.url = incoming.url.replace(/^\/calendar/, '/calendar.html');
        }
        next();
      });
    },

    generateBundle(_options, bundle) {
      const precacheSet = new Set<string>([
        './',
        './index.html',
        './calendar.html',
        './team-spirit-emblem.png',
      ]);
      const fingerprintInputs: string[] = [];

      for (const item of Object.values(bundle)) {
        const fileName = item.fileName;
        if (fileName === 'sw.js' || fileName.endsWith('.map')) {
          continue;
        }
        if (item.type === 'chunk' && item.code.trim().length === 0) {
          continue;
        }
        if (PRECACHE_EXT_RE.test(fileName)) {
          precacheSet.add(`./${fileName}`);
        }
        if (item.type === 'chunk') {
          fingerprintInputs.push(`${fileName}:${item.code.length}`);
        } else {
          const size =
            typeof item.source === 'string' ? item.source.length : item.source.byteLength;
          fingerprintInputs.push(`${fileName}:${size}`);
        }
      }

      fingerprintInputs.sort();
      const precacheUrls = Array.from(precacheSet).sort();
      const cacheVersion = computeBuildFingerprint([
        ...precacheUrls,
        ...fingerprintInputs,
      ]);

      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: buildServiceWorkerSource(cacheVersion, precacheUrls, supabaseOrigin),
      });
    },
  };
}
